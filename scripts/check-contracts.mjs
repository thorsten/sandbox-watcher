#!/usr/bin/env node
// Type-checks the Rust serialisation fixtures against src/types.ts.
//
// crates/sandbox-core/tests/contracts.rs (and src-tauri/src/contracts.rs)
// write fixtures/contracts/<Type>.json: what the Rust side serialises for
// every enum variant and every optional field. This script turns each
// sample into `const x: T.<Type> = <json>` and lets tsc reject it, which
// catches missing fields, unknown fields, wrong enum spellings and wrong
// nullability. fixtures/contracts/enums.json adds the other direction for
// enums: a TypeScript union member that Rust never produces fails too.
//
// Usage: node scripts/check-contracts.mjs [--keep]
//   --keep   leave the generated project in target/contracts for inspection

import { createRequire } from "node:module";
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const fixturesDir = join(root, "fixtures", "contracts");
const outDir = join(root, "target", "contracts");
const keep = process.argv.includes("--keep");

const files = readdirSync(fixturesDir)
  .filter((f) => f.endsWith(".json") && f !== "enums.json")
  .toSorted();
if (files.length === 0) {
  console.error(`no fixtures in ${fixturesDir}; run the Rust contract tests first`);
  process.exit(1);
}

const lines = [
  "// Generated by scripts/check-contracts.mjs from fixtures/contracts. Do not edit.",
  'import type * as T from "../../src/types";',
  "",
  "type Equal<A, B> =",
  "  (<X>() => X extends A ? 1 : 2) extends <X>() => X extends B ? 1 : 2 ? true : false;",
  "type Expect<X extends true> = X;",
  "",
];

let samples = 0;
for (const file of files) {
  const doc = JSON.parse(readFileSync(join(fixturesDir, file), "utf8"));
  if (typeof doc.type !== "string" || !Array.isArray(doc.samples)) {
    console.error(`${file}: expected { "type": string, "samples": [...] }`);
    process.exit(1);
  }
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(doc.type)) {
    console.error(`${file}: "${doc.type}" is not a plain type name`);
    process.exit(1);
  }
  lines.push(`// ${file}`);
  doc.samples.forEach((sample, i) => {
    lines.push(
      `export const ${doc.type}_${i}: T.${doc.type} = ${JSON.stringify(sample, null, 2)};`,
    );
    samples += 1;
  });
  lines.push("");
}

const enums = JSON.parse(readFileSync(join(fixturesDir, "enums.json"), "utf8"));
lines.push("// enums.json: every TypeScript union member must be one Rust produces");
for (const [name, entry] of Object.entries(enums)) {
  if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name)) {
    console.error(`enums.json: "${name}" is not a plain type name`);
    process.exit(1);
  }
  const values = JSON.stringify([...new Set(entry.values)]);
  const union = entry.tag ? `T.${name}[${JSON.stringify(entry.tag)}]` : `T.${name}`;
  lines.push(
    `export const ${name}_values = ${values} as const satisfies readonly ${union}[];`,
    `export type ${name}_exhaustive = Expect<`,
    `  Equal<Exclude<${union}, (typeof ${name}_values)[number]>, never>`,
    `>;`,
  );
}
lines.push("");

mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, "contracts.ts"), lines.join("\n"));
writeFileSync(
  join(outDir, "tsconfig.json"),
  JSON.stringify(
    {
      extends: "../../tsconfig.json",
      compilerOptions: { noEmit: true, types: [] },
      include: ["contracts.ts"],
    },
    null,
    2,
  ),
);

const require = createRequire(import.meta.url);
const tsc = require.resolve("typescript/bin/tsc");
const result = spawnSync(process.execPath, [tsc, "-p", join(outDir, "tsconfig.json"), "--pretty"], {
  cwd: root,
  stdio: "inherit",
});
if (!keep) {
  rmSync(outDir, { recursive: true, force: true });
}
if (result.status !== 0) {
  console.error(
    `\ncontract check failed: ${files.length} fixture files types did not all type-check against src/types.ts.` +
      `\nFix src/types.ts, or if the Rust side changed on purpose, regenerate the fixtures:` +
      `\n  SANDBOX_WATCHER_UPDATE_CONTRACTS=1 cargo test -p sandbox-core --test contracts` +
      `\nRe-run with --keep to inspect target/contracts/contracts.ts.`,
  );
  process.exit(result.status ?? 1);
}
console.log(
  `contracts ok: ${samples} samples in ${files.length} types and ${Object.keys(enums).length} enums match src/types.ts`,
);
